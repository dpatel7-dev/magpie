'use strict';
// Watching the clipboard, and putting things back on it.
//
// On a Mac, one small JavaScript-for-Automation program (macOS's own
// scripting, nothing to install) checks the clipboard's change counter a few
// times a second, which costs next to nothing. When it changes, it reports
// what was copied and from which app. Things a password manager marks as
// secret ("concealed") are never even read.
// Elsewhere, magpie asks the system clipboard tool every second.

const fs = require('fs');
const os = require('os');
const path = require('path');
const { spawn, spawnSync } = require('child_process');

const MAC = process.platform === 'darwin';
const FAKE = () => process.env.MAGPIE_FAKE_CLIPBOARD; // tests: a file stands in for the clipboard

// the watcher, run by osascript -l JavaScript; one line of JSON per copy
const WATCHER = `
ObjC.import('AppKit');
ObjC.import('Foundation');
function say(o) {
  var s = $(JSON.stringify(o) + '\\n');
  $.NSFileHandle.fileHandleWithStandardOutput.writeData(s.dataUsingEncoding($.NSUTF8StringEncoding));
}
function has(types, t) { return types.indexOf(t) >= 0; }
function run(argv) {
  var dir = argv[0];
  var pb = $.NSPasteboard.generalPasteboard;
  var last = pb.changeCount;
  say({ ready: true, change: last });
  while (true) {
    delay(0.3);
    var c = pb.changeCount;
    if (c === last) continue;
    last = c;
    var types = ObjC.deepUnwrap(pb.types) || [];
    var front = $.NSWorkspace.sharedWorkspace.frontmostApplication;
    var o = { change: c, at: Date.now(), app: front.isNil() ? '' : ObjC.unwrap(front.localizedName), bundle: front.isNil() ? '' : ObjC.unwrap(front.bundleIdentifier) };
    if (has(types, 'org.nspasteboard.ConcealedType') || has(types, 'org.nspasteboard.TransientType') || has(types, 'org.nspasteboard.AutoGeneratedType') || has(types, 'com.agilebits.onepassword')) {
      o.secret = true; say(o); continue;
    }
    if (has(types, 'public.file-url')) {
      var items = pb.pasteboardItems;
      var files = [];
      if (!items.isNil()) for (var i = 0; i < items.count; i++) {
        var u = items.objectAtIndex(i).stringForType('public.file-url');
        if (!u.isNil()) { var url = $.NSURL.URLWithString(u); if (!url.isNil() && !url.path.isNil()) files.push(ObjC.unwrap(url.path)); }
      }
      if (files.length) { o.files = files; say(o); continue; }
    }
    var s = pb.stringForType($.NSPasteboardTypeString);
    if (!s.isNil()) o.text = ObjC.unwrap(s);
    if (!o.text && (has(types, 'public.png') || has(types, 'public.tiff'))) {
      var data = pb.dataForType('public.png');
      if (data.isNil()) {
        var tiff = pb.dataForType('public.tiff');
        if (!tiff.isNil()) { var rep = $.NSBitmapImageRep.imageRepWithData(tiff); if (!rep.isNil()) data = rep.representationUsingTypeProperties($.NSBitmapImageFileTypePNG, $.NSDictionary.dictionary); }
      }
      if (!data.isNil() && data.length < 40000000) {
        var file = dir + '/new-' + c + '-' + Date.now() + '.png';
        data.writeToFileAtomically(file, true);
        o.image = file;
      }
    }
    say(o);
  }
}
`;

/** Read one line of the watcher's output (also used by the tests). */
function parse(line) {
  try { const o = JSON.parse(line); return o && typeof o === 'object' ? o : null; } catch { return null; }
}

/**
 * Start watching. onCopy({ text | image | files | secret, app, bundle, at }).
 * Returns { stop }.
 */
function start(onCopy, { imagesDir, onError = () => {} } = {}) {
  if (FAKE()) return fakeWatch(onCopy);
  if (MAC) return macWatch(onCopy, imagesDir, onError);
  return pollWatch(onCopy);
}

function macWatch(onCopy, imagesDir, onError) {
  let child = null, stopped = false, wait = 1000;
  const script = path.join(imagesDir, '..', 'watcher.js');
  fs.mkdirSync(imagesDir, { recursive: true, mode: 0o700 });
  fs.writeFileSync(script, WATCHER);
  const go = () => {
    if (stopped) return;
    const began = Date.now();
    child = spawn('osascript', ['-l', 'JavaScript', script, imagesDir], { stdio: ['ignore', 'pipe', 'pipe'] });
    let buf = '';
    child.stdout.on('data', (d) => {
      buf += d;
      let i;
      while ((i = buf.indexOf('\n')) >= 0) {
        const o = parse(buf.slice(0, i));
        buf = buf.slice(i + 1);
        if (o && !o.ready) onCopy(o);
      }
    });
    let err = '';
    child.stderr.on('data', (d) => { err = (err + d).slice(-500); });
    child.on('exit', () => {
      if (stopped) return;
      if (Date.now() - began > 60000) wait = 1000;
      onError(new Error(`the clipboard watcher stopped${err ? ': ' + err.trim().split('\n').pop() : ''}; starting it again`));
      setTimeout(go, wait);
      wait = Math.min(60000, wait * 2);
    });
  };
  go();
  return { stop() { stopped = true; if (child) child.kill(); } };
}

function pollWatch(onCopy) {
  let last = read(), stopped = false;
  const t = setInterval(() => {
    if (stopped) return;
    const now = read();
    if (now !== null && now !== last) { last = now; onCopy({ text: now, at: Date.now(), app: '', bundle: '' }); }
  }, 1000);
  return { stop() { stopped = true; clearInterval(t); } };
}

function fakeWatch(onCopy) {
  let last = read();
  const t = setInterval(() => {
    const now = read();
    if (now !== null && now !== last) { last = now; onCopy({ text: now, at: Date.now(), app: 'Tests', bundle: 'dev.test' }); }
  }, 100);
  return { stop() { clearInterval(t); } };
}

// ── the clipboard itself ──
const UTF8 = { ...process.env, LC_ALL: 'en_US.UTF-8', LANG: 'en_US.UTF-8' };

function read() {
  if (FAKE()) { try { return fs.readFileSync(FAKE(), 'utf8'); } catch { return null; } }
  const tries = MAC ? [['pbpaste', []]] : process.platform === 'win32' ? [['powershell', ['-NoProfile', '-Command', 'Get-Clipboard -Raw']]] : [['wl-paste', ['-n']], ['xclip', ['-selection', 'clipboard', '-o']], ['xsel', ['-b', '-o']]];
  for (const [cmd, args] of tries) {
    const r = spawnSync(cmd, args, { encoding: 'utf8', timeout: 3000, env: UTF8 });
    if (r.status === 0) return r.stdout;
  }
  return null;
}

function setText(text) {
  if (FAKE()) { fs.writeFileSync(FAKE(), text); return true; }
  const tries = MAC ? [['pbcopy', []]] : process.platform === 'win32' ? [['clip', []]] : [['wl-copy', []], ['xclip', ['-selection', 'clipboard']], ['xsel', ['-b', '-i']]];
  for (const [cmd, args] of tries) {
    const r = spawnSync(cmd, args, { input: text, timeout: 5000, env: UTF8, stdio: ['pipe', 'ignore', 'ignore'] });
    if (r.status === 0) return true;
  }
  return false;
}

function setImage(file) {
  if (FAKE()) { fs.writeFileSync(FAKE(), `[image ${path.basename(file)}]`); return true; }
  if (!MAC) return false;
  const code = `ObjC.import('AppKit'); function run(a) { var d = $.NSData.dataWithContentsOfFile(a[0]); var pb = $.NSPasteboard.generalPasteboard; pb.clearContents; pb.setDataForType(d, 'public.png'); return 'ok'; }`;
  return spawnSync('osascript', ['-l', 'JavaScript', '-e', code, file], { timeout: 8000 }).status === 0;
}

function setFiles(files) {
  if (FAKE()) { fs.writeFileSync(FAKE(), files.join('\n')); return true; }
  if (!MAC) return setText(files.join('\n'));
  const code = `ObjC.import('AppKit'); function run(a) { var pb = $.NSPasteboard.generalPasteboard; pb.clearContents; var urls = $.NSMutableArray.array; for (var i = 0; i < a.length; i++) urls.addObject($.NSURL.fileURLWithPath(a[i])); pb.writeObjects(urls); return 'ok'; }`;
  return spawnSync('osascript', ['-l', 'JavaScript', '-e', code, ...files], { timeout: 8000 }).status === 0;
}

module.exports = { start, parse, read, setText, setImage, setFiles, WATCHER, tmpDir: os.tmpdir };
